export function makeT(lang) {
  const dict = S[lang] || S.ua;
  return (key, vars) => {
    let v = dict[key] ?? S.ua[key] ?? key;
    if (vars && typeof v === 'string') for (const k in vars) v = v.replaceAll(`{${k}}`, vars[k]);
    return v;
  };
}

